#include <stdio.h>

int main() {
    //Inisialisasi variabel
    int x = 5;
    int y = 7;
    int z = 9;

    //Menampilkan hasil penjumlahan
    int jumlah = x + y + z;

    //Menampilkan output
    printf("Variabel x bernilai %d\n", x);
    printf("Variabel y bernilai %d\n", y);  
    printf("Variabel z bernilai %d\n", z);
    printf("Jumlah variabel tersebut adalah %d\n", jumlah);
    
    return 0;
}