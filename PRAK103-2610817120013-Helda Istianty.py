#Inisialisasi variabel
a = 9
b = 6
x = 10
y = 7

#Menghitung kombinasi pertambahan, perkalian, dan pembagian 
hasil = (a + b) * x / y

#Menampilkan output
print(f"Varibel a bernilai {a}")
print(f"Varibel b bernilai {b}")
print(f"Varibel x bernilai {x}")
print(f"Varibel y bernilai {y}")
print(f"Hasil dari (a + b) dikali x dibagi y adalah {hasil}")
print(f"Hasil dari a ditambah b dikali x dibagi y adalah {hasil:.2f}")