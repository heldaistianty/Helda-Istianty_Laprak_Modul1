# Inisialisasi variabel
a = 4
b = 8
c = 3

# Pengecekan perbandingan (diubah ke int agar menghasilkan 1 atau 0)
cek1 = int(a == b)
cek2 = int(b > c)
cek3 = int(a != c)

# Menampilkan output
print(f"Variabel a bernilai {a}")
print(f"Variabel b bernilai {b}")
print(f"Variabel c bernilai {c}")
print(f"Apakah a sama dengan b ? jawabannya adalah {cek1}")
print(f"Apakah b lebih besar dari c ? jawabannya adalah {cek2}")
print(f"Apakah a tidak sama dengan c ? jawabannya adalah {cek3}")