# Inisialisasi variabel panjang sisi segitiga
a = 4
b = 5
c = 7

# Inisialisasi biaya pagar per meter
biaya_per_meter = 85000

# Menghitung keliling dan total biaya
keliling = a + b + c
total_biaya = keliling * biaya_per_meter

# Menampilkan output
print("Diketahui :")
print(f"Panjang sisi segitiga berturut-turut adalah {a}, {b}, dan {c}")
print(f"Keliling Tanah Pak Dengklek adalah {keliling}")
print(f"Harga tanah Per Meter adalah {biaya_per_meter}")
print("Jawaban :")
print(f"Biaya yang diperlukan Pak Dengklek adalah : Rp {total_biaya}")